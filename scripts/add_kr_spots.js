let added = 0;
Object.entries(CITIES).forEach(([city, list]) => {
  list.forEach(([name, en, lng, lat, tags, rating, desc], i) => {
    if (spots.some(s => s.city === city && s.name === name)) return;
    spots.push({
      spot_id: 'kr_' + city + '_' + i,
      name, city, province: '韩国', region: 'ab',
      address: city + ' · ' + name,
      lng, lat, hours: '2 小时', traffic: '', price: '',
      rating, heat: 72, tags, desc, img: '',
      geo_src: 'manual', src: '人工整理坐标'
    });
    added++;
  });
});

