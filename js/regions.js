/* ---- 索引：城市/地区 → 所属省·国；景点 → 所属区域 ---- */
const _cityIndex={};
['cn','ab'].forEach(k=>{
  REGIONS[k].forEach(g=>{
    g.pKey=k;
    g.c.forEach(c=>{ _cityIndex[c]={p:g.p,key:k} });
  });
});
const _norm=s=>String(s||'').replace(/(省|市|州|地区|盟|自治区|特别行政区)$/,'');

/** 景点所属区域：优先按城市名精确/去后缀匹配，其次按国家名匹配 */
function regionOfSpot(s){
  if(!s)return null;
  if(_cityIndex[s.city])return _cityIndex[s.city];
  const hit=Object.keys(_cityIndex).find(c=>s.city&&(s.city.includes(c)||c.includes(_norm(s.city))));
  if(hit)return _cityIndex[hit];
  return null;
}

/** 某省内所有城市；某国内所有州/地区 */
function citiesOf(prov,key){ const g=REGIONS[key].find(x=>x.p===prov); return g?g.c.slice():[]; }
function regionsOfCountry(country){ return citiesOf(country,'ab'); }

/** 城市里已收录的景点（用于结果卡片与路线推荐） */
function spotsOfCity(city){
  const n=_norm(city);
  return SPOTS.filter(s=>s.city===city||_norm(s.city)===n||s.city.includes(city)||city.includes(_norm(s.city)));
}
/** 省份/国家里所有已收录景点 */
function spotsOfRegion(prov){
  return SPOTS.filter(s=>{const r=regionOfSpot(s);return r&&r.p===prov});
}

/** 转盘候选：返回 [{label, sub, spotId}] */
function wheelCandidates(scope,prov,city){
  if(city){                       /* 精确到单个城市/州 */
    const sps=spotsOfCity(city);
    if(sps.length)return sps.map(s=>({label:s.n,sub:city,spotId:s.id}));
    return [{label:city,sub:prov,spotId:null}];
  }
  const list=citiesOf(prov,scope==='cn'?'cn':'ab');
  return list.map(c=>{const sps=spotsOfCity(c);return {label:c,sub:prov,spotId:sps[0]?sps[0].id:null}});
}
